"""Build "Music Library Backup.app" and install it in the Applications folder.

The bundle is a small launcher: it runs app_qt.py from this project with
the project's .venv, so code changes show up without rebuilding. Rebuild
after bumping VERSION so Finder shows the new version.

    .venv/bin/python make_launcher.py            # build and install
    .venv/bin/python make_launcher.py --no-install
"""

import argparse
import os
import plistlib
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from PySide6.QtWidgets import QApplication

import app_qt


PROJECT_DIR = Path(__file__).resolve().parent
BUILD_DIR = PROJECT_DIR / "build"
BUNDLE_NAME = app_qt.APP_NAME + ".app"
BUNDLE_ID = "local.musiclibrarybackup"
EXECUTABLE = "launcher"

LAUNCHER_SCRIPT = """#!/bin/zsh
# Generated by make_launcher.py. Runs the app from its project folder.

PROJECT_DIR={project}
PYTHON="$PROJECT_DIR/.venv/bin/python"

if [[ ! -f "$PROJECT_DIR/app_qt.py" ]]; then
    osascript -e 'display alert "Music Library Backup" message "The project folder was moved or deleted. Run make_launcher.py again from its new location."'
    exit 1
fi

if [[ ! -x "$PYTHON" ]] || ! "$PYTHON" -c "import PySide6" 2>/dev/null; then
    osascript -e 'display alert "Music Library Backup" message "Open \\"Music Library Backup.command\\" in the project folder once to set up Python and PySide6."'
    exit 1
fi

cd "$PROJECT_DIR"
exec "$PYTHON" app_qt.py
"""


def info_plist():
    return {
        "CFBundleName": app_qt.APP_NAME,
        "CFBundleDisplayName": app_qt.APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": EXECUTABLE,
        "CFBundleIconFile": "AppIcon",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": app_qt.VERSION,
        "CFBundleVersion": app_qt.VERSION,
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
    }


def write_icon(resources_dir):
    with tempfile.TemporaryDirectory() as temp:
        iconset = Path(temp) / "AppIcon.iconset"
        iconset.mkdir()

        for size in (16, 32, 128, 256, 512):
            app_qt.make_icon_pixmap(size).save(
                str(iconset / f"icon_{size}x{size}.png")
            )
            app_qt.make_icon_pixmap(size * 2).save(
                str(iconset / f"icon_{size}x{size}@2x.png")
            )

        subprocess.run(
            [
                "iconutil",
                "-c",
                "icns",
                str(iconset),
                "-o",
                str(resources_dir / "AppIcon.icns"),
            ],
            check=True,
        )


def build_bundle(output_dir):
    """Write the .app into output_dir and return its path."""
    QApplication.instance() or QApplication([])

    bundle = Path(output_dir) / BUNDLE_NAME

    if bundle.exists():
        shutil.rmtree(bundle)

    macos_dir = bundle / "Contents" / "MacOS"
    resources_dir = bundle / "Contents" / "Resources"
    macos_dir.mkdir(parents=True)
    resources_dir.mkdir()

    with (bundle / "Contents" / "Info.plist").open("wb") as file:
        plistlib.dump(info_plist(), file)

    launcher = macos_dir / EXECUTABLE
    launcher.write_text(
        LAUNCHER_SCRIPT.format(project=shlex.quote(str(PROJECT_DIR))),
        encoding="utf-8",
    )
    launcher.chmod(0o755)

    write_icon(resources_dir)

    return bundle


def is_our_bundle(bundle):
    try:
        with (bundle / "Contents" / "Info.plist").open("rb") as file:
            return plistlib.load(file).get("CFBundleIdentifier") == BUNDLE_ID
    except (OSError, plistlib.InvalidFileException):
        return False


def install(bundle):
    """Copy the bundle into /Applications, or ~/Applications if that's not writable."""
    for applications in (Path("/Applications"), Path.home() / "Applications"):
        if applications == Path.home() / "Applications":
            applications.mkdir(exist_ok=True)

        if not os.access(applications, os.W_OK):
            continue

        target = applications / bundle.name

        if target.exists():
            if not is_our_bundle(target):
                sys.exit(
                    "Refusing to replace " + str(target)
                    + ": it isn't a bundle built by make_launcher.py."
                )
            shutil.rmtree(target)

        shutil.copytree(bundle, target, symlinks=True)

        # Ask Finder and Launch Services to pick up the new icon and version.
        os.utime(target)
        subprocess.run(
            [
                "/System/Library/Frameworks/CoreServices.framework/Frameworks/"
                "LaunchServices.framework/Support/lsregister",
                "-f",
                str(target),
            ],
            check=False,
        )

        return target

    sys.exit("No writable Applications folder found.")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--no-install",
        action="store_true",
        help="only build into build/, don't copy into Applications",
    )
    args = parser.parse_args()

    BUILD_DIR.mkdir(exist_ok=True)
    bundle = build_bundle(BUILD_DIR)
    print("Built " + str(bundle) + " (version " + app_qt.VERSION + ")")

    if not args.no_install:
        target = install(bundle)
        print("Installed " + str(target))


if __name__ == "__main__":
    main()
